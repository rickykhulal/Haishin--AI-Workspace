/**
 * Demo response service for Haishin v0.1.
 *
 * All responses from this module are pre-written mock content.
 * No trained model is running. This exists to demonstrate the chat UI.
 */

export interface ChatRequest {
  conversationId: string;
  messages: Array<{ role: "user" | "assistant"; content: string }>;
  modelId: string;
}

export interface ChatResponse {
  message: {
    role: "assistant";
    content: string;
  };
  mode: "mock" | "haishin" | "external";
}

