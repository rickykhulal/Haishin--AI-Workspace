let responseIndex = 0;

/**
 * Simulates a model response with a realistic delay.
 * Returns mode: "mock" so the UI can label the source honestly.
 */
export function sendDemoRequest(
  _request: ChatRequest,
  signal?: AbortSignal,
): Promise<ChatResponse> {
  const delay = 800 + Math.random() * 1200;
  const content = DEMO_RESPONSES[responseIndex % DEMO_RESPONSES.length]!;
  responseIndex++;

  return new Promise((resolve, reject) => {
    const timer = setTimeout(() => {
      resolve({
        message: { role: "assistant", content },
        mode: "mock",
      });
    }, delay);

    signal?.addEventListener("abort", () => {
      clearTimeout(timer);
      reject(new DOMException("Demo request aborted", "AbortError"));
    });
  });
}

/**
 * Generates a conversation title from the first user message.
 */
export function generateTitle(firstMessage: string): string {
  const trimmed = firstMessage.trim();
  if (trimmed.length <= 50) return trimmed;
  return trimmed.slice(0, 47) + "...";
}
